import { Pool } from "pg";
import { createDemoDatabase } from "../lib/db";
import { POSTGRES_SCHEMA, postgresConnection, postgresSql } from "../lib/postgres-sql";

const connectionString = process.env.DATABASE_URL;
if (!connectionString) throw new Error("Set DATABASE_URL to initialize the hosted demo database.");

const AMENITY_GUARD = `
CREATE OR REPLACE FUNCTION ensure_amenity_slot() RETURNS trigger
LANGUAGE plpgsql SET search_path TO ${POSTGRES_SCHEMA}, pg_catalog AS $body$
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext(NEW."amenityId"));
  IF EXISTS (
    SELECT 1 FROM society_amenity_reservation
    WHERE "amenityId" = NEW."amenityId" AND id <> NEW.id
      AND "startsAt" < NEW."endsAt" AND "endsAt" > NEW."startsAt"
  ) THEN
    RAISE EXCEPTION 'amenity reservation overlaps'
      USING ERRCODE = '23P01', CONSTRAINT = 'jodo_amenity_reservation_overlap';
  END IF;
  RETURN NEW;
END
$body$;
DROP TRIGGER IF EXISTS society_amenity_reservation_no_overlap ON society_amenity_reservation;
CREATE TRIGGER society_amenity_reservation_no_overlap
BEFORE INSERT OR UPDATE OF "amenityId", "startsAt", "endsAt" ON society_amenity_reservation
FOR EACH ROW EXECUTE FUNCTION ensure_amenity_slot();
`;

function postgresDefinition(sql: string) {
  const ddl = sql
    .replace(/^CREATE (TABLE|(?:UNIQUE )?INDEX) /i, "CREATE $1 IF NOT EXISTS ")
    .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/gi, "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace(/\b(\w+Paise) INTEGER\b/g, "$1 BIGINT")
    .replace(/\bBLOB\b/g, "BYTEA")
    .replace(/\s+COLLATE NOCASE\b/gi, "");
  return postgresSql(ddl);
}

async function initialize() {
  const pool = new Pool({ ...postgresConnection(connectionString!), max: 1, connectionTimeoutMillis: 15_000 });
  const source = createDemoDatabase();
  try {
    const client = await pool.connect();
    try {
      await client.query(`BEGIN;
        SELECT pg_advisory_xact_lock(110415234, 1);
        CREATE SCHEMA IF NOT EXISTS ${POSTGRES_SCHEMA};
        REVOKE ALL ON SCHEMA ${POSTGRES_SCHEMA} FROM PUBLIC;
        SET LOCAL search_path TO ${POSTGRES_SCHEMA}, pg_catalog;`);
      const objects = source.prepare(`SELECT name, type, sql FROM sqlite_master
        WHERE type IN ('table', 'index') AND sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid`).all() as {
        name: string; type: "table" | "index"; sql: string;
      }[];
      for (const { sql } of objects) await client.query(postgresDefinition(sql));
      await client.query(postgresSql(`
        ALTER TABLE notification ADD COLUMN IF NOT EXISTS gateVisitId TEXT;
        CREATE UNIQUE INDEX IF NOT EXISTS jodo_amenity_name_ci ON society_amenity(societyId, lower(name));
        CREATE UNIQUE INDEX IF NOT EXISTS jodo_vendor_invoice_ci
          ON society_finance_expenses(societyId, lower(vendor), lower(invoiceReference)) WHERE kind = 'vendor_bill';
        CREATE UNIQUE INDEX IF NOT EXISTS jodo_direct_expense_ci
          ON society_finance_expenses(societyId, label, lower(vendor), amountPaise, incurredOn, lower(paymentReference)) WHERE kind = 'expense';
      `));
      await client.query(AMENITY_GUARD);
      const hasData = (await client.query("SELECT 1 FROM society LIMIT 1")).rowCount;
      if (!hasData) {
        for (const table of objects.filter((item) => item.type === "table")) {
          const records = source.prepare(`SELECT * FROM "${table.name}"`).all();
          if (!records.length) continue;
          const fields = Object.keys(records[0]);
          const rowParams = `(${fields.map(() => "?").join(", ")})`;
          const rows = records.map(() => rowParams).join(", ");
          const insert = postgresSql(`INSERT INTO ${table.name} (${fields.join(", ")}) VALUES ${rows}`);
          await client.query(insert, records.flatMap((row) => fields.map((field) => row[field])));
          if (/\bAUTOINCREMENT\b/.test(table.sql)) {
            const maxId = records.reduce((max, row) => Math.max(max, Number(row.id)), 0);
            await client.query("SELECT setval(pg_get_serial_sequence($1, 'id'), $2, true)", [table.name, maxId]);
          }
        }
      }
      await client.query("COMMIT");
      console.log(hasData ? "Verified the existing JODO schema." : "Initialized the private JODO schema with demo data.");
    } catch (error) {
      await client.query("ROLLBACK").catch(() => {});
      throw error;
    } finally {
      client.release();
    }
  } finally {
    source.close();
    await pool.end();
  }
}

initialize().catch((error: Error & { code?: string }) => {
  console.error(`JODO database initialization failed${error.code ? ` [${error.code}]` : ""}: ${error.message}`);
  process.exitCode = 1;
});
